/** Базовый интервал опроса, когда всё отвечает. */
export const POLL_MS = 3000;

/** Потолок отступа. Дальше расти незачем: дев-сервер поднимут и опрос
 *  вернётся к базовому темпу с первого же успешного ответа. */
export const MAX_BACKOFF_MS = 30_000;

/**
 * Следующая задержка опроса.
 *
 * Без отступа поллер при упавшем дев-сервере долбит эндпоинт с базовым
 * интервалом бесконечно, забивая консоль ошибками и держа сеть занятой.
 * Здесь задержка удваивается на каждой ошибке до потолка и сбрасывается
 * в базовую с первого успеха — восстановление мгновенное, а не постепенное.
 */
export function nextDelay(current: number, ok: boolean): number {
  if (ok) return POLL_MS;
  return Math.min(current * 2, MAX_BACKOFF_MS);
}
